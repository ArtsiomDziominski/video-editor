"""TikTok «Отдали камеру»: события и надписи. Выполняется внутри beats.py."""

L_ = lambda n: A.VOICE_AT[n - 1]         # начало фразы (номер с единицы)
E_ = lambda n: A.VOICE_AT[n - 1] + A.LINES[n - 1]["duration"]   # конец фразы
END = A.DURATION


def slams(ch, key, n, t0, t1, label):
    """Свечи падают по очереди, равномерно на отрезке."""
    for i in range(n):
        ev(ch, f"{key}{i}", t0 + (t1 - t0) * i / n, f"{label} {i + 1}", "thud")


def wipe(ch, key, t, label):
    """Короткая шторка: в момент t она закрыла кадр."""
    t = ev(ch, key, t, label)
    SOUND_EVENTS.append((t - 0.22, "whoosh", 0.45, label))
    SOUND_EVENTS.append((t, "clunk", 0, ""))


