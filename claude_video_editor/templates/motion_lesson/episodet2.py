"""TikTok «Подожди закрытия»: события и надписи. Выполняется внутри beats.py."""

L_ = lambda n: A.VOICE_AT[n - 1]         # начало фразы (номер с единицы)
END = A.DURATION


def wipe(ch, key, t, label):
    """Короткая шторка: в момент t она закрыла кадр."""
    t = ev(ch, key, t, label)
    SOUND_EVENTS.append((t - 0.22, "whoosh", 0.45, label))
    SOUND_EVENTS.append((t, "clunk", 0, ""))


def rewinding(ch, key, t0, t1, label):
    """Часы бегут от t0 до t1: тиканье и звук перемотки."""
    ev(ch, key, t0, label, "ticking", t1 - t0)
    SOUND_EVENTS.append((t0, "rewind", t1 - t0, ""))


