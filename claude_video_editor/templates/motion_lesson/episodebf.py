"""TikTok «Фильтр для фотографий, который торгует тренд» (Bilateral Filter Trend, ≈75 с): события и надписи. Выполняется внутри beats.py."""

L_ = lambda n: A.VOICE_AT[n - 1]         # начало фразы (номер с единицы)
END = A.DURATION


def wipe(ch, key, t, label):
    """Короткая шторка: в момент t она закрыла кадр."""
    t = ev(ch, key, t, label)
    SOUND_EVENTS.append((t - 0.22, "whoosh", 0.45, label))
    SOUND_EVENTS.append((t, "clunk", 0, ""))


# ---------- 1. Крючок: шумное фото гор, фильтр, силуэт становится графиком ----------
tx("s1", "a_hook", "ФИЛЬТР ДЛЯ ФОТО…\nТОРГУЕТ ТРЕНД?", 0, "ФИЛЬТР ДЛЯ ФОТО… ТОРГУЕТ ТРЕНД? — с первого кадра: фото гор, под ним свечи того же силуэта")
ev("s1", "a_sweep", W_(1, "чистить"), "полоса фильтра проходит по фото: шум исчезает", "soft_whoosh", 1.4)
SOUND_EVENTS.append((END - 0.75, "hiss", 0.75 + EV["a_sweep"] + 1.3, "шипение шума: из конца ролика в начало, гаснет за полосой фильтра"))
ev("s1", "a_edge", W_(1, "края"), "край гор остаётся чётким: по нему бежит блик")
ev("s1", "a_morph", W_(1, "надели"), "край гор отрывается от фото и падает на свечи", "click")
ev("s1", "a_chart", W_(1, "графи"), "линия легла на свечи ровной линией сквозь их дрожь", "thud")
ev("s1", "a_strat", W_(1, "стратегия"), "линия вспыхивает: вверх зелёная, вниз красная", "ding")

# ---------- 2. Обычная средняя опаздывает ----------
ev("s2", "b_move", L_(4) - 0.3, "камера вдоль графика: свечи идут вверх", "soft_whoosh", 1.0)
tx("s2", "b_avg", "СРЕДНЯЯ", W_(2, "средняя"), None, "click")
ev("s2", "b_turn", W_(2, "развороте"), "свечи резко разворачиваются вниз", "skid")
tx("s2", "b_late", "ОБЫЧНАЯ СРЕДНЯЯ\nОПАЗДЫВАЕТ", W_(2, "развороте"), None)
ev("s2", "b_pull", W_(2, "тянут"), "средняя ещё идёт вверх: зазор краснеет")
SOUND_EVENTS.append((EV["b_pull"], "hum", max(1.0, L_(6) - 0.15 - EV["b_pull"]), "низкий гул на красном зазоре"))

# ---------- 3. В чём фокус ----------
tx("s3", "c_s1", "ВОЗРАСТ", W_(3, "возраст"), None, "click")
tx("s3", "c_s2", "РАССТОЯНИЕ", W_(3, "далеко"), None, "click")
tx("s3", "c_t1", "ДАЛЁКИЕ СВЕЧИ\nНЕ ВЕСЯТ", W_(3, "далекого"), None)
ev("s3", "c_melt", W_(3, "весят"), "свечи старого уровня тают", "melt", 1.2)
ev("s3", "c_line", W_(3, "резко"), "линия фильтра поворачивает вслед за графиком", "whoosh", 0.5)
ev("s3", "c_calm", W_(3, "дрожь"), "камера к мелкой дрожи: линия ровная", "soft_whoosh", 0.9)

# ---------- 4. Одно правило ----------
ev("s4", "d_move", L_(10) - 0.3, "камера к новому тренду", "soft_whoosh", 1.0)
tx("s4", "d_up", "ЛОНГ", W_(4, "вверх"), "ЛОНГ ⬆", "ding")
ev("s4", "d_flip", W_(4, "развернулась"), "линия разворачивается и краснеет", "whoosh", 0.4)
tx("s4", "d_short", "ШОРТ", W_(4, "шорт"), "ЛОНГ зачёркнут → ШОРТ ⬇", "click")
tx("s4", "d_close", "ТОЛЬКО\nПО ЗАКРЫТИЮ", W_(4, "закрытой"), None, "tick")
ev("s4", "d_four", W_(4, "четырех"), "часы на свече: круг замкнулся, свеча закрылась", "latch")

# ---------- 5. Защита ----------
ev("s5", "e_move", L_(15) - 0.3, "камера к точке входа", "soft_whoosh", 0.9)
for key, stem in (("e_r1", "три"), ("e_r2", "средних"), ("e_r3", "размаха")):
    ev("s5", key, W_(5, stem), "отрезок размаха свечи", "thud")
tx("s5", "e_ruler", "РАЗМАХ СВЕЧИ ×3", EV["e_r3"] + 0.25, None)
tx("s5", "e_lock", "СТОП", W_(5, "входа"), None, "latch")
tx("s5", "e_risk", "РИСК 2%", W_(5, "двух"), None, "click")

# ---------- 6. Честная статистика ----------
wipe("s6", "f_wipe", L_(18) - 0.12, "шторка: десять квадратиков")
ev("s6", "f_sq", W_(6, "удачных"), "квадратики загораются по очереди")
GREEN = (1, 4, 8)
for k in range(10):
    SOUND_EVENTS.append((EV["f_sq"] + 0.14 * k, "ding" if k in GREEN else "thud", 0, ""))
tx("s6", "f_t1", "УДАЧНЫХ\nМЕНЬШЕ ТРЕТИ —", W_(6, "трети"), None)
ev("s6", "f_cols", W_(6, "удачные"), "зелёный столбик растёт втрое выше красного", "noise_rise", 1.5)
tx("s6", "f_t2", "НО ОНИ В 3 РАЗА\nКРУПНЕЕ", W_(6, "крупнее"), None, "hit")
ev("s6", "f_cut", W_(6, "режет"), "красный столбик срезан стопом", "latch")
ev("s6", "f_hold", W_(6, "держит"), "зелёный столбик светится", "ding")

# ---------- 7. Слабое место ----------
wipe("s7", "g_wipe", L_(22) - 0.12, "шторка: боковик")
tx("s7", "g_t", "БОКОВИК —\nСЛАБОЕ МЕСТО", W_(7, "боковик"), None, "click")
ev("s7", "g_chop", W_(7, "дергается"), "линия мечется: зелёный, красный, зелёный")
for k, (stem, nth) in enumerate((("туда", 0), ("срабатывает", 0), ("раз", 0), ("разом", 0))):
    ev("s7", f"g_s{k + 1}", W_(7, stem, nth), "линия развернулась, стоп вспыхивает", "buzz")
    SOUND_EVENTS.append((EV[f"g_s{k + 1}"] - 0.08, "click", 0, ""))
ev("s7", "g_norm", W_(7, "нормально"), "серия крестиков")
ev("s7", "g_big", W_(7, "редких"), "большой тренд: камера отъезжает", "soft_whoosh", 1.4)
SOUND_EVENTS.append((W_(7, "трендов"), "ding", 0, ""))

# ---------- 8. Итог и петля ----------
tx("s8", "h_title", "BILATERAL\nFILTER TREND", L_(26) - 0.25, None, "ding")
for key, name, stem in (("h_1", "1. ЛИНИЯ ВВЕРХ — ЛОНГ", "фильтр"), ("h_2", "2. РАЗВОРОТ — ПЕРЕВОРОТ", "правило"), ("h_3", "3. СТОП ВСЕГДА", "стоп")):
    tx("s8", key, name, W_(8, stem), None, "thud")
tx("s8", "h_note", "Обучающий ролик, не совет.\nИстория не гарантирует будущего", EV["h_title"] + 0.5)
ev("s8", "z_back", END - 1.7, "график сматывается назад и снова становится фото гор", "soft_whoosh", 1.1)
