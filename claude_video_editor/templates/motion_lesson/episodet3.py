"""TikTok «Что такое ICO»: события и надписи. Выполняется внутри beats.py."""

L_ = lambda n: A.VOICE_AT[n - 1]         # начало фразы (номер с единицы)
END = A.DURATION


def wipe(ch, key, t, label):
    """Короткая шторка: в момент t она закрыла кадр."""
    t = ev(ch, key, t, label)
    SOUND_EVENTS.append((t - 0.22, "whoosh", 0.45, label))
    SOUND_EVENTS.append((t, "clunk", 0, ""))


# ---------- 1. Крючок ----------
launch = W_(1, "через")
SOUND_EVENTS.append((END - 1.0, "engine", 1.0 + launch, "рокот двигателя: идёт из конца ролика в начало, обрывается на взлёте"))
tx("s1", "a_hook", "ЗАЛЕТАЙ,\nПОКА РАНО!", 0, "ЗАЛЕТАЙ, ПОКА РАНО! — с первого кадра")
ev("s1", "a_shine", W_(1, "новый"), "блик по обёртке", "clink")
ev("s1", "a_launch", launch, "стрелка взмывает вверх", "rocket", 1.4)
tx("s1", "a_x100", "×100", W_(1, "сто"), "×100", "hit")
ev("s1", "a_ask", L_(2), "берёшь?", "pop")

# ---------- 2. Что такое ICO ----------
ev("s2", "b_pan", L_(3) - 0.2, "камера к чертежу", "soft_whoosh", 0.9)
