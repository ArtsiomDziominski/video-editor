tx("s2", "b_sub", "ПЕРВИЧНАЯ ПРОДАЖА\nТОКЕНОВ", W_(2, "первичная"), None, "click")
ev("s2", "b_house", W_(2, "команда"), "чертёж недостроенного дома")
ev("s2", "b_tickets", W_(2, "продает"), "билетики улетают к чертежу")
for k in range(5):
    SOUND_EVENTS.append((EV["b_tickets"] + 0.24 * k, "rustle", 0.22, ""))

# ---------- 3. Что ты получаешь ----------
ev("s3", "c_move", L_(5) - 0.1, "камера к трём коробкам", "soft_whoosh", 0.9)
for key, stem in (("c_b1", "товар"), ("c_b2", "доля")):
    ev("s3", key, W_(3, stem), None, "clunk")
    SOUND_EVENTS.append((EV[key] + 0.32, "thud", 0, ""))      # крестик
ev("s3", "c_b3", W_(3, "токен"), "коробка с билетиком", "clunk")
SOUND_EVENTS.append((EV["c_b3"] + 0.32, "ding", 0, ""))
ev("s3", "c_q", W_(3, "вера"), "знак вопроса над токеном", "question")

# ---------- 4. За обёрткой ----------
ev("s4", "d_back", L_(7) - 0.15, "камера назад к обёртке", "whoosh", 0.5)
tx("s4", "d_t1", "ЗАГЛЯНЕМ\nЗА ОБЁРТКУ", W_(4, "заглянем"), None, "click")
ev("s4", "d_flip", W_(4, "обертку"), "обёртка распахивается: внутри пусто", "flip")
SOUND_EVENTS.append((EV["d_flip"] + 0.45, "echo", 0, ""))
tx("s4", "d_folder", "ПЛАН НА 40 СТРАНИЦ", EV["d_flip"] + 0.75, None, "pop")
ev("s4", "d_many", W_(4, "тысячи", 1), "десять таких же коробок", "rustle", 0.5)
ev("s4", "d_empty", W_(4, "оказались"), "восемь из десяти — пустые", "rustle", 0.8)
tx("s4", "d_t2", "8 ИЗ 10 —\nПУСТЫШКИ", W_(4, "пустышками"), None, "hit")

# ---------- 5. Три вопроса ----------
wipe("s5", "e_wipe", L_(10) - 0.12, "шторка: три вопроса")
for key, name, n in (("e_q1", "1. КТО КОМАНДА?", 11), ("e_q2", "2. ЕСТЬ ЛИ ПРОДУКТ?", 12), ("e_q3", "3. СКОЛЬКО ТОКЕНОВ\nУ КОМАНДЫ?", 13)):
    tx("s5", key, name, L_(n), None, "step")
    SOUND_EVENTS.append((EV[key] + 0.13, "step", 0, ""))
SOUND_EVENTS.append((EV["e_q3"] + 0.45, "rustle", 0.3, "лента обхватывает стопку"))
